-- Módulo: Zonas, Empleados (vendedores y cajeros), Clientes y Comisiones
CREATE TABLE IF NOT EXISTS zona (
    zona_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(80) NOT NULL UNIQUE,
    activo  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS empleado (
    empleado_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(120) NOT NULL,
    telefono            VARCHAR(20) NOT NULL,
    domicilio           VARCHAR(200) NOT NULL,
    tipo                VARCHAR(10) NOT NULL,
    porcentaje_comision DECIMAL(5,2) NOT NULL,
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    zona_id             BIGINT NULL,
    CONSTRAINT fk_empleado_zona FOREIGN KEY (zona_id) REFERENCES zona (zona_id),
    CONSTRAINT ck_empleado_tipo CHECK (tipo IN ('VENDEDOR', 'CAJERO')),
    CONSTRAINT ck_empleado_porcentaje CHECK (porcentaje_comision >= 0 AND porcentaje_comision <= 100),
    CONSTRAINT ck_empleado_zona CHECK ((tipo = 'VENDEDOR' AND zona_id IS NOT NULL) OR (tipo = 'CAJERO' AND zona_id IS NULL))
);

CREATE TABLE IF NOT EXISTS cliente (
    cliente_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(120) NOT NULL,
    rfc              VARCHAR(13) NOT NULL UNIQUE,
    domicilio        VARCHAR(200) NOT NULL,
    telefono         VARCHAR(20) NOT NULL,
    telefono_alterno VARCHAR(20) NULL,
    contacto         VARCHAR(120) NULL,
    limite_credito   DECIMAL(12,2) NOT NULL DEFAULT 0,
    dias_credito     INT NOT NULL DEFAULT 0,
    activo           BOOLEAN NOT NULL DEFAULT TRUE,
    zona_id          BIGINT NOT NULL,
    CONSTRAINT fk_cliente_zona FOREIGN KEY (zona_id) REFERENCES zona (zona_id),
    CONSTRAINT ck_cliente_credito CHECK (limite_credito >= 0 AND dias_credito >= 0)
);

-- venta_id / factura_id se guardan sin FK para no acoplar el orden de creación de tablas entre módulos
CREATE TABLE IF NOT EXISTS comision (
    comision_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_generacion    DATE NOT NULL,
    importe_comision    DECIMAL(12,2) NOT NULL,
    importe_venta       DECIMAL(12,2) NOT NULL,
    porcentaje_aplicado DECIMAL(5,2) NOT NULL,
    venta_id            BIGINT NULL,
    factura_id          BIGINT NULL,
    empleado_id         BIGINT NOT NULL,
    estado              VARCHAR(10) NOT NULL DEFAULT 'GENERADA',
    CONSTRAINT fk_comision_empleado FOREIGN KEY (empleado_id) REFERENCES empleado (empleado_id),
    CONSTRAINT ck_comision_estado CHECK (estado IN ('GENERADA', 'CANCELADA'))
);
