-- Módulo: Pedidos (venta no directa), Facturación y Cuentas por cobrar
CREATE TABLE IF NOT EXISTS pedido (
    pedido_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pedido  DATE NOT NULL,
    fecha_entrega DATE NOT NULL,
    cliente_id    BIGINT NOT NULL,
    vendedor_id   BIGINT NOT NULL,
    dias_credito  INT NOT NULL DEFAULT 0,
    subtotal      DECIMAL(12,2) NOT NULL,
    iva           DECIMAL(12,2) NOT NULL,
    total         DECIMAL(12,2) NOT NULL,
    estado        VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT fk_pedido_vendedor FOREIGN KEY (vendedor_id) REFERENCES empleado (empleado_id),
    CONSTRAINT ck_pedido_estado CHECK (estado IN ('PENDIENTE', 'ENTREGADO', 'FACTURADO', 'CANCELADO'))
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
    detalle_pedido_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id          BIGINT NOT NULL,
    articulo_id        BIGINT NOT NULL,
    codigo             VARCHAR(30) NOT NULL,
    descripcion        VARCHAR(120) NOT NULL,
    cantidad_pedida    INT NOT NULL,
    cantidad_pendiente INT NOT NULL,
    precio             DECIMAL(12,2) NOT NULL,
    importe            DECIMAL(12,2) NOT NULL,
    promesa            BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_dpedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (pedido_id),
    CONSTRAINT ck_dpedido_cantidades CHECK (cantidad_pedida > 0 AND cantidad_pendiente >= 0
        AND cantidad_pendiente <= cantidad_pedida)
);

CREATE TABLE IF NOT EXISTS factura (
    factura_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_factura        DATE NOT NULL,
    dias_credito         INT NOT NULL DEFAULT 0,
    fecha_limite_pago    DATE NOT NULL,
    subtotal             DECIMAL(12,2) NOT NULL,
    iva                  DECIMAL(12,2) NOT NULL,
    total                DECIMAL(12,2) NOT NULL,
    estado               VARCHAR(10) NOT NULL DEFAULT 'EMITIDA',
    venta_id             BIGINT NULL,
    pedido_id            BIGINT NULL,
    cliente_id           BIGINT NOT NULL,
    vendedor_id          BIGINT NOT NULL,
    sustituye_factura_id BIGINT NULL,
    CONSTRAINT fk_factura_venta FOREIGN KEY (venta_id) REFERENCES venta (venta_id),
    CONSTRAINT fk_factura_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (pedido_id),
    CONSTRAINT fk_factura_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT fk_factura_vendedor FOREIGN KEY (vendedor_id) REFERENCES empleado (empleado_id),
    CONSTRAINT fk_factura_sustituye FOREIGN KEY (sustituye_factura_id) REFERENCES factura (factura_id),
    CONSTRAINT ck_factura_estado CHECK (estado IN ('EMITIDA', 'CANCELADA')),
    CONSTRAINT ck_factura_origen CHECK ((venta_id IS NOT NULL AND pedido_id IS NULL) OR (venta_id IS NULL AND pedido_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS factura_detalle (
    factura_detalle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id         BIGINT NOT NULL,
    articulo_id        BIGINT NOT NULL,
    codigo             VARCHAR(30) NOT NULL,
    descripcion        VARCHAR(120) NOT NULL,
    cantidad           INT NOT NULL,
    precio             DECIMAL(12,2) NOT NULL,
    importe            DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_fdetalle_factura FOREIGN KEY (factura_id) REFERENCES factura (factura_id)
);

CREATE TABLE IF NOT EXISTS cuenta_por_cobrar (
    cuenta_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_cuenta      DATE NOT NULL,
    fecha_facturacion DATE NOT NULL,
    fecha_limite      DATE NOT NULL,
    estado            VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE',
    importe_original  DECIMAL(12,2) NOT NULL,
    importe_pendiente DECIMAL(12,2) NOT NULL,
    factura_id        BIGINT NOT NULL UNIQUE,
    cliente_id        BIGINT NOT NULL,
    CONSTRAINT fk_cxc_factura FOREIGN KEY (factura_id) REFERENCES factura (factura_id),
    CONSTRAINT fk_cxc_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT ck_cxc_estado CHECK (estado IN ('PENDIENTE', 'PARCIAL', 'LIQUIDADA', 'CANCELADA')),
    CONSTRAINT ck_cxc_importes CHECK (importe_pendiente >= 0 AND importe_pendiente <= importe_original)
);

CREATE TABLE IF NOT EXISTS pago_cuenta_por_cobrar (
    pago_cuenta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id      BIGINT NOT NULL,
    fecha_pago     DATE NOT NULL,
    importe        DECIMAL(12,2) NOT NULL,
    forma_pago     VARCHAR(15) NOT NULL,
    CONSTRAINT fk_pagocxc_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta_por_cobrar (cuenta_id),
    CONSTRAINT ck_pagocxc_importe CHECK (importe > 0)
);
