-- Módulo: Inventario simulado (solo lectura/descuento vía InventarioGateway), Ventas directas, Pago, Ticket y Corte de caja

-- Réplica mínima del catálogo de Inventario. Ventas NUNCA la toca directo: usa la interfaz InventarioGateway.
CREATE TABLE IF NOT EXISTS articulo_ref (
    articulo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(30) NOT NULL UNIQUE,
    nombre      VARCHAR(120) NOT NULL,
    precio      DECIMAL(12,2) NOT NULL,
    existencias INT NOT NULL,
    CONSTRAINT ck_articulo_existencias CHECK (existencias >= 0)
);

CREATE TABLE IF NOT EXISTS corte_caja (
    corte_caja_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_id          INT NOT NULL,
    cajero_id        BIGINT NOT NULL,
    fecha_apertura   TIMESTAMP NOT NULL,
    hora_corte       TIMESTAMP NULL,
    importe_inicial  DECIMAL(12,2) NOT NULL,
    total_ventas     INT NOT NULL DEFAULT 0,
    importe_esperado DECIMAL(12,2) NULL,
    importe_fisico   DECIMAL(12,2) NULL,
    diferencia       DECIMAL(12,2) NULL,
    hay_diferencia   BOOLEAN NOT NULL DEFAULT FALSE,
    estado           VARCHAR(10) NOT NULL DEFAULT 'ABIERTA',
    CONSTRAINT fk_corte_cajero FOREIGN KEY (cajero_id) REFERENCES empleado (empleado_id),
    CONSTRAINT ck_corte_estado CHECK (estado IN ('ABIERTA', 'CERRADA'))
);

CREATE TABLE IF NOT EXISTS venta (
    venta_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_venta      TIMESTAMP NOT NULL,
    cajero_id        BIGINT NOT NULL,
    corte_caja_id    BIGINT NOT NULL,
    cliente_id       BIGINT NULL,
    solicita_factura BOOLEAN NOT NULL DEFAULT FALSE,
    subtotal         DECIMAL(12,2) NOT NULL,
    iva              DECIMAL(12,2) NOT NULL,
    total            DECIMAL(12,2) NOT NULL,
    estado           VARCHAR(12) NOT NULL DEFAULT 'COMPLETADA',
    CONSTRAINT fk_venta_cajero FOREIGN KEY (cajero_id) REFERENCES empleado (empleado_id),
    CONSTRAINT fk_venta_corte FOREIGN KEY (corte_caja_id) REFERENCES corte_caja (corte_caja_id),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT ck_venta_estado CHECK (estado IN ('COMPLETADA', 'CANCELADA'))
);

CREATE TABLE IF NOT EXISTS venta_detalle (
    venta_detalle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT NOT NULL,
    articulo_id      BIGINT NOT NULL,
    codigo           VARCHAR(30) NOT NULL,
    descripcion      VARCHAR(120) NOT NULL,
    cantidad         INT NOT NULL,
    precio           DECIMAL(12,2) NOT NULL,
    importe          DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_vdetalle_venta FOREIGN KEY (venta_id) REFERENCES venta (venta_id),
    CONSTRAINT ck_vdetalle_cantidad CHECK (cantidad > 0)
);

CREATE TABLE IF NOT EXISTS pago (
    pago_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT NOT NULL UNIQUE,
    forma_pago       VARCHAR(15) NOT NULL,
    importe          DECIMAL(12,2) NOT NULL,
    importe_recibido DECIMAL(12,2) NOT NULL,
    cambio           DECIMAL(12,2) NOT NULL,
    fecha_pago       TIMESTAMP NOT NULL,
    CONSTRAINT fk_pago_venta FOREIGN KEY (venta_id) REFERENCES venta (venta_id),
    CONSTRAINT ck_pago_forma CHECK (forma_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA'))
);

CREATE TABLE IF NOT EXISTS ticket (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id  BIGINT NOT NULL UNIQUE,
    folio     VARCHAR(20) NOT NULL,
    contenido VARCHAR(2000) NOT NULL,
    fecha     TIMESTAMP NOT NULL,
    CONSTRAINT fk_ticket_venta FOREIGN KEY (venta_id) REFERENCES venta (venta_id)
);
